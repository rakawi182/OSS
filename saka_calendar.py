BULAN_SAKA_ORDER = [
    "Chaitra", "Vaisakha", "Jyestha", "Asadha",
    "Sravana", "Bhadrapada", "Asvini", "Kartika",
    "Margasira", "Pausa", "Magha", "Phalguna"
]

def is_kabisat(saka_year: int) -> bool:
    return saka_year in INTERCALATION_LOOKUP

def get_punah_month(saka_year: int):
    return INTERCALATION_LOOKUP.get(saka_year)

def get_months_in_year(saka_year: int) -> list:
    months = []
    punah = get_punah_month(saka_year)
    for bulan in BULAN_SAKA_ORDER:
        months.append(bulan)
        if punah and bulan == punah:
            months.append(f"Punah {punah}")
    return months

def get_month_sequence(saka_year: int) -> list:
    months = []
    punah = get_punah_month(saka_year)
    for bulan in BULAN_SAKA_ORDER:
        months.append(bulan)
        if punah and bulan == punah:
            months.append(bulan)
    return months