        moon_data = self.calculate_complete_lunar_position(
            year_astro, month, day, hour, minute, second,
            output_frame='horizontal',
            observer_lat_deg=self.site_lat,
            observer_lon_deg=self.site_lon,
            observer_elevation_m=self.site_elev
        )
        
        # --- 4. Hitung fase bulan secara terpisah (sudah ada di moon_data? Pastikan) ---
        if 'lunar_phase' not in moon_data:
            moon_phase = self.calculate_lunar_phase(year_astro, month, day, hour, minute, second)
            moon_data['lunar_phase'] = moon_phase
        
