def format_ra_hms(ra_deg):
    """Konversi derajat RA ke format HH:MM:SS.ss"""
    if ra_deg is None:
        return "N/A"
    hours = ra_deg / 15.0
    h = int(hours)
    m = int((hours - h) * 60)
    s = ((hours - h) * 60 - m) * 60
    return f"{h:02d}h {m:02d}m {s:05.2f}s"

def format_dec_dms(dec_deg):
    """Konversi derajat Dec ke format ±DD°MM'SS.ss\" """
    if dec_deg is None:
        return "N/A"
    sign = '-' if dec_deg < 0 else '+'
    dec_abs = abs(dec_deg)
    d = int(dec_abs)
    m = int((dec_abs - d) * 60)
    s = ((dec_abs - d) * 60 - m) * 60
    return f"{sign}{d:02d}° {m:02d}' {s:05.2f}\""

