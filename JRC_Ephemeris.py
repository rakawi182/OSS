    def calculate_complete_lunar_position(self, year_astro, month, day,
                                         hour=0, minute=0, second=0,
                                         output_frame='horizontal',
                                         observer_lat_deg=None, observer_lon_deg=None,
                                         observer_elevation_m=None,
                                         pressure_hPa=952.5, temperature_c=22.9,
                                         humidity=0.728,
                                         use_gamma_prime_correction=True):
        """
        Hitung posisi Bulan topocentric/horizontal lengkap beserta metadata,
        menyerupai output Matahari dari calculate_complete_sun_position.
        
        Parameters:
            year_astro, month, day, hour, minute, second : waktu lokal WIB
            output_frame : 'horizontal' (default) → dapatkan semua data termasuk alt/az,
                           'topocentric' → hanya koordinat ekuatorial topocentric,
                           'equatorial_apparent' → geosentrik apparent, dll.
            observer_*   : koordinat pengamat (default Jolotundo)
            pressure, temperature, humidity : untuk refraksi atmosfer
            use_gamma_prime_correction : gunakan koreksi γ'2000 ke mean equinox
        
        Returns:
            dictionary lengkap (sama seperti keluaran LunarELP82Engine.calculate_position
            dengan frame topocentric/horizontal)
        """
        if self.lunar_engine is None:
            return {'error': 'Lunar engine not available'}

        # Default ke situs Jolotundo
        if observer_lat_deg is None:
            observer_lat_deg = self.site_lat
        if observer_lon_deg is None:
            observer_lon_deg = self.site_lon
        if observer_elevation_m is None:
            observer_elevation_m = self.site_elev

        # Konversi WIB ke JD UTC
        jd_utc = self.time_sys.wib_to_jd_utc(year_astro, month, day, hour, minute, second)

        # Panggil engine dengan frame yang diminta
        result = self.lunar_engine.calculate_position(
            jd_utc,
            output_frame=output_frame,
            observer_lat_deg=observer_lat_deg,
            observer_lon_deg=observer_lon_deg,
            observer_elevation_m=observer_elevation_m,
            pressure_hPa=pressure_hPa,
            temperature_c=temperature_c,
            humidity=humidity,
            use_gamma_prime_correction=use_gamma_prime_correction
        )

        # Tambahkan informasi fase Bulan (opsional)
        try:
            phase_info = self.calculate_lunar_phase(year_astro, month, day, hour, minute, second)
            if 'error' not in phase_info:
                result['lunar_phase'] = phase_info
        except Exception as e:
            result['lunar_phase'] = {'error': str(e)}
        
        # ------------------------------------------------------------------
        # 10. Moon rise, set, transit (hanya untuk frame horizontal)
        # ------------------------------------------------------------------
        if output_frame == 'horizontal':
            try:
                # KUNCI PERBAIKAN: Hitung Julian Day tepat di jam 00:00:00 waktu lokal
                jd_local_midnight_utc = self.time_sys.wib_to_jd_utc(year_astro, month, day, 0, 0, 0)
                
                moon_rise_set = self.topo_corr.calculate_moon_rise_set_transit(
                    jd_local_midnight_utc,
                    observer_lat_deg,
                    observer_lon_deg,
                    observer_elevation_m,
                    self.lunar_engine
                )
                result['moon_rise_set_transit'] = moon_rise_set
            except Exception as e:
                result['moon_rise_set_transit'] = {'error': str(e)}

        return result
        
    def calculate_lunar_phase(self, year_astro, month, day, hour=0, minute=0, second=0):
        """
        Calculate precise lunar phase based on Ecliptic Longitude difference.
        Dilengkapi penanganan error dan nilai default.
        """
        if self.lunar_engine is None:
            return {
                'elongation_deg': 0.0,
                'illumination_fraction': 0.0,
                'phase_name': 'Unknown (engine unavailable)',
                'error': 'Lunar engine not available'
            }

        try:
            jd_utc = self.time_sys.wib_to_jd_utc(year_astro, month, day, hour, minute, second)

            # Sun position in ecliptic apparent
            sun_data = self.sun_calc.calculate_sun_position_vsop87d(
                self.time_sys.jd_utc_to_tt_extended(jd_utc), 'ecliptic_apparent'
            )

            # Moon position in ecliptic apparent (geocentric) – tanpa parameter 'topocentric'
            moon_data = self.calculate_complete_lunar_position(
                year_astro, month, day, hour, minute, second,
                output_frame='ecliptic_apparent'
            )

            if 'error' in sun_data or 'error' in moon_data:
                raise ValueError("Ephemeris error")

            # Ambil bujur ekliptika
            sun_lon = sun_data.get('longitude_deg')
            moon_lon = moon_data.get('ecliptic_apparent', {}).get('longitude_deg')

            if sun_lon is None or moon_lon is None:
                raise ValueError("Missing longitude data")

            age_deg = (moon_lon - sun_lon) % 360.0
            illum_fraction = (1.0 - math.cos(math.radians(age_deg))) / 2.0
            phase_name = self._phase_name(age_deg)

            return {
                'julian_day_utc': jd_utc,
                'elongation_deg': age_deg,
                'illumination_fraction': illum_fraction,
                'phase_name': phase_name,
                'sun_lon': sun_lon,
                'moon_lon': moon_lon
            }
        except Exception as e:
            # Kembalikan nilai default agar tidak merusak cetakan
            return {
                'elongation_deg': 0.0,
                'illumination_fraction': 0.0,
                'phase_name': 'Unknown (calculation error)',
                'error': str(e)
            }
    
    def _phase_name(self, age_deg):
        """Map 0-360 degree moon age to phase name."""
        # Standard astronomical definitions based on ecliptic longitude difference
        a = age_deg % 360.0
        
        if a < 22.5 or a >= 337.5:
            return "New Moon"
        elif 22.5 <= a < 67.5:
            return "Waxing Crescent"
        elif 67.5 <= a < 112.5:
            return "First Quarter"
        elif 112.5 <= a < 165.0:
            return "Waxing Gibbous"
        elif 165.0 <= a < 195.0:
            return "Full Moon"
        elif 195.0 <= a < 247.5:
            return "Waning Gibbous"
        elif 247.5 <= a < 292.5:
            return "Last Quarter"
        else: # 292.5 <= a < 337.5
            return "Waning Crescent"

