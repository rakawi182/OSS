    def _calculate_basic_sunrise_sunset(self, jd_utc: float, lat: float, lon: float,
                                       dec_deg: float) -> Dict[str, Any]:
        """Basic sunrise/sunset calculation fallback"""
        # Simplified calculation without full VSOP87
        h0 = -0.8333
        lat_rad = np.radians(lat)
        dec_rad = np.radians(dec_deg)
        
        cos_HA = (np.sin(np.radians(h0)) - np.sin(lat_rad) * np.sin(dec_rad)) / \
                (np.cos(lat_rad) * np.cos(dec_rad))
        
        if cos_HA > 1 or cos_HA < -1:
            HA = 0
        else:
            HA = np.degrees(np.arccos(np.clip(cos_HA, -1.0, 1.0)))
        
        transit_utc = (12.0 - lon/15.0) % 24
        sunrise_utc = (transit_utc - HA/15.0) % 24
        sunset_utc = (transit_utc + HA/15.0) % 24
        
        def format_time(hours):
            h = int(hours)
            m = int((hours - h) * 60)
            s = ((hours - h) * 60 - m) * 60
            return f"{h:02d}:{m:02d}:{int(s):02d}"
        
        return {
            'sunrise': {
                'wib': format_time((sunrise_utc + 7) % 24),
                'utc': format_time(sunrise_utc),
                'local_time': (sunrise_utc + 7) % 24
            },
            'sunset': {
                'wib': format_time((sunset_utc + 7) % 24),
                'utc': format_time(sunset_utc),
                'local_time': (sunset_utc + 7) % 24
            },
            'transit': {
                'wib': format_time((transit_utc + 7) % 24),
                'utc': format_time(transit_utc),
                'local_time': (transit_utc + 7) % 24,
                'altitude': 0,
                'azimuth': 0
            },
            'day_length': 2 * HA/15.0,
            'night_length': 24 - (2 * HA/15.0),
            'equation_of_time_minutes': 0,
            'hour_angle_deg': HA,
            'declination': dec_deg
        }

