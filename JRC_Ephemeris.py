    # --------------------------------------------------------------------
    # 6. Fungsi pembantu
    # --------------------------------------------------------------------
    def _ecliptic_to_equatorial(self, lon_rad: float, lat_rad: float, eps_rad: float) -> Tuple[float, float]:
        """Konversi koordinat ekliptika ke ekuatorial."""
        sin_lon = math.sin(lon_rad)
        cos_lon = math.cos(lon_rad)
        sin_lat = math.sin(lat_rad)
        cos_lat = math.cos(lat_rad)
        sin_eps = math.sin(eps_rad)
        cos_eps = math.cos(eps_rad)

        y = sin_lon * cos_eps - math.tan(lat_rad) * sin_eps
        x = cos_lon
        ra_rad = math.atan2(y, x)
        if ra_rad < 0:
            ra_rad += 2 * math.pi

        sin_dec = sin_lat * cos_eps + cos_lat * sin_eps * sin_lon
        dec_rad = math.asin(max(min(sin_dec, 1.0), -1.0))
        return ra_rad, dec_rad

    def compute_mean_obliquity_of_date(self, T: float) -> float:
        """Hitung mean obliquity of date (ε₀) dalam radian - IAU 2006."""
        U = T / 100.0
        eps0_arcsec = 84381.406 - 46.836769 * U - 0.0001831 * U**2 + 0.00200340 * U**3 - 0.000000576 * U**4 - 0.0000000434 * U**5
        return math.radians(eps0_arcsec / 3600.0)

    def compute_enhanced_nutation(self, T: float) -> Tuple[float, float, float, float]:
        """Hitung nutasi yang ditingkatkan dengan koreksi abad ke-21."""
        cache_key = f"enhanced_nutation_{T:.10f}"

        def compute():
            # Nutasi dasar dari HighPrecisionNutation
            dPsi_as, dEps_as = self.nutation.compute(T)
            dPsi_rad = math.radians(dPsi_as)
            dEps_rad = math.radians(dEps_as)

            # Mean obliquity J2000
            eps0_rad = math.radians(self.const.OBLIQUITY_J2000)

            # True obliquity
            eps_true_rad = eps0_rad + dEps_rad

            # Koreksi abad ke-21 (IERS 2010)
            T2 = T * T
            T3 = T2 * T
            psi_corr = (0.194 + 0.0007 * T + 0.000001 * T2) / 3600.0 * math.pi / 180.0
            eps_corr = (0.077 + 0.0003 * T + 0.000001 * T2) / 3600.0 * math.pi / 180.0

            dPsi_rad += psi_corr
            dEps_rad += eps_corr
            eps_true_rad += eps_corr

            return dPsi_rad, dEps_rad, eps0_rad, eps_true_rad

        return self.cache.get_or_compute('nutation', cache_key, compute)


