    def analyze_archaeological_alignment(self, jd_utc: float,
                                       target_azimuth_deg: float,
                                       target_altitude_deg: float,
                                       observer_lat_deg: float = None,
                                       observer_lon_deg: float = None,
                                       tolerance_azimuth_deg: float = 1.0,
                                       tolerance_altitude_deg: float = 0.5) -> Dict[str, Any]:
        """
        Analyze if Sun aligns with archaeological feature at given time.
        
        Parameters:
        - jd_utc: Julian Date in UTC
        - target_azimuth_deg: Azimuth of archaeological alignment
        - target_altitude_deg: Altitude of alignment (horizon altitude)
        - observer_lat_deg, observer_lon_deg: Observer location
        - tolerance_azimuth_deg: Acceptance tolerance for azimuth match
        - tolerance_altitude_deg: Acceptance tolerance for altitude match
        
        Returns alignment analysis with match quality.
        """
        if observer_lat_deg is None or observer_lon_deg is None:
            observer_lat_deg = self.const.JOLOTUNDO_LOCATION['coordinates']['latitude']
            observer_lon_deg = self.const.JOLOTUNDO_LOCATION['coordinates']['longitude']
        
        # Get Sun position
        sun_data = self.calculate_sun_topocentric_observed(
            jd_utc, observer_lat_deg, observer_lon_deg
        )
        
        sun_az = sun_data['horizontal_coordinates']['azimuth_deg']
        sun_alt = sun_data['horizontal_coordinates']['altitude_apparent_deg']
        
        # Calculate differences
        azimuth_diff = self._angular_difference(sun_az, target_azimuth_deg)
        altitude_diff = sun_alt - target_altitude_deg
        
        # Determine if aligned (within tolerances)
        azimuth_aligned = abs(azimuth_diff) <= tolerance_azimuth_deg
        altitude_aligned = abs(altitude_diff) <= tolerance_altitude_deg
        fully_aligned = azimuth_aligned and altitude_aligned
        
        # Calculate alignment quality score (0-100)
        azimuth_score = max(0, 100 - (abs(azimuth_diff) / tolerance_azimuth_deg) * 100)
