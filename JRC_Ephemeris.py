class GlobalCacheManager:
    """Unified cache management system with LRU and memory limits"""
    
    _instance = None
    _caches = {
        'nutation': OrderedDict(),
        'sun_position': OrderedDict(),
        'moon_position': OrderedDict(),
        'lunar_position': OrderedDict(),              # ← ADD THIS LINE
        'atmospheric': OrderedDict(),
        'coordinate': OrderedDict()
    }
    
    _max_sizes = {
        'nutation': 500,
        'sun_position': 1000,
        'moon_position': 1000,
        'lunar_position': 1000,              # ← ADD THIS LINE
        'atmospheric': 200,
        'coordinate': 500
    }
    
    @classmethod
    def get_instance(cls):
        if cls._instance is None:
            cls._instance = cls()
        return cls._instance
    
    def __init__(self):
        self.stats = {
            'hits': {k: 0 for k in self._caches.keys()},
            'misses': {k: 0 for k in self._caches.keys()},
            'total': {k: 0 for k in self._caches.keys()}
        }
    
    def get_or_compute(self, cache_type: str, key: str, compute_func, *args, **kwargs):
        """Get from cache or compute and store"""
        if cache_type not in self._caches:
            raise ValueError(f"Unknown cache type: {cache_type}")
        
        if key in self._caches[cache_type]:
            self.stats['hits'][cache_type] += 1
            result = self._caches[cache_type][key]
            # Move to end (most recently used)
            self._caches[cache_type].move_to_end(key)
            return result
        
        self.stats['misses'][cache_type] += 1
        result = compute_func(*args, **kwargs)
        
        # Apply LRU eviction if needed
        if len(self._caches[cache_type]) >= self._max_sizes[cache_type]:
            self._caches[cache_type].popitem(last=False)
        
        self._caches[cache_type][key] = result
        return result
    
    def clear_cache(self, cache_type: Optional[str] = None):
        """Clear specific cache or all caches"""
        if cache_type:
            if cache_type in self._caches:
                self._caches[cache_type].clear()
        else:
            for cache in self._caches.values():
                cache.clear()
        gc.collect()
    
    def get_stats(self) -> Dict[str, Any]:
        """Get cache statistics"""
        stats = {}
        for cache_type in self._caches.keys():
            total = self.stats['hits'][cache_type] + self.stats['misses'][cache_type]
            if total > 0:
                hit_rate = self.stats['hits'][cache_type] / total
            else:
                hit_rate = 0.0
            stats[cache_type] = {
                'size': len(self._caches[cache_type]),
                'max_size': self._max_sizes[cache_type],
                'hits': self.stats['hits'][cache_type],
                'misses': self.stats['misses'][cache_type],
                'hit_rate': hit_rate
            }
        return stats
    
    def clear_all(self):
        """Clear all caches and reset stats"""
        self.clear_cache()
        self.stats = {
            'hits': {k: 0 for k in self._caches.keys()},
            'misses': {k: 0 for k in self._caches.keys()},
            'total': {k: 0 for k in self._caches.keys()}
        }


