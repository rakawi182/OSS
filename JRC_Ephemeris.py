    def is_gregorian_date(self, year_astro, month, day):
        """
        Tentukan apakah tanggal menggunakan Kalender Gregorian
        SEKARANG: Gunakan tahun astronomi murni
        """
        # Gregorian dimulai 15 Oktober 1582 (tahun astronomi 1582)
        if year_astro < 1582:
            return False
        elif year_astro > 1582:
            return True
        else:  # year_astro == 1582
            if month < 10:
                return False
            elif month > 10:
                return True
            else:  # month == 10
                return day >= 15
    
    def is_leap_year(self, year_astro):
        """
        Tentukan tahun kabisat - SEKARANG: Gunakan tahun astronomi murni
        """
        if self.is_gregorian_date(year_astro, 1, 1):
            if year_astro % 100 == 0:
                return year_astro % 400 == 0
            return year_astro % 4 == 0
        else:
            return year_astro % 4 == 0
    
