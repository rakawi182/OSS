class VSOP87SolarEngine:
    """
    Engine perhitungan posisi Matahari menggunakan VSOP87D penuh.
    Memanfaatkan modul VSOP87D_Earth untuk menghitung koordinat Bumi heliosentrik,
    kemudian dikonversi menjadi posisi Matahari geosentrik.
    """

    def __init__(self, vsop87_data_file="VSOP87D_ear.txt"):
        self.const = IAU2023UltraPrecision()
        self.cache = GlobalCacheManager.get_instance()
        self.time_sys = TimeSystem()
        self.nutation = HighPrecisionNutation()
        self.transformer = UnifiedCoordinateTransformer()

