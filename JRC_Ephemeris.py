def test_lunar_elp82b_vs_jpl_horizons():
    """
    Perbandingan langsung posisi Bulan antara JAE Lunar Engine dan JPL Horizons (DE441).
    **Sistem koordinat disamakan secara eksplisit.**

    ========================================================================
    KESETARAAN SISTEM KOORDINAT
    ========================================================================
    JPL Horizons (file horizons_results (1).txt):
        - Kerangka   : Apparent of-date (true equator & equinox of date)
        - Model      : Presesi/nutasi IAU76/80 + EOP
        - Equinox    : offset -53 mas terhadap kerangka IAU06/00a
        - Aberasi    : Annual + diurnal (bintang)
        - Paralaks   : Diurnal (toposentrik) → data ini GEOSENTRIK, jadi tidak ada paralaks
        - Data       : R.A.__(a-apparent)__DEC (kolom ke-4 & 5)

    JAE Lunar Engine (LunarELP82Engine):
        - Kerangka   : Apparent of-date (true equator & equinox of date)
        - Model      : Presesi IAU2006, nutasi IAU2000A (25 terms)
        - Aberasi    : Annual aberration (konstanta 20.49552″)
        - Paralaks   : Tidak diterapkan (geosentrik)
        - γ'2000     : Koreksi gamma prime (+0.0000275°) → mean equinox of date

    Perbedaan kerangka yang perlu dikoreksi:
        1. Offset equinox: kerangka JPL (IAU76/80) memiliki RA origin lebih barat 0.053″
           dibanding kerangka IAU06/00a (yang digunakan JAE).
           → RA JAE harus dikurangi 0.053″ agar sama dengan JPL.

        2. Nutasi: perbedaan antara IAU76/80 dan IAU2000A pada epoch 2024 < 0.01″,
           diabaikan (jauh di bawah toleransi arkeoastronomi 10″).

        3. Presesi: ELP2000-82B menghasilkan koordinat dalam dynamical ecliptic of date,
           yang setelah koreksi γ'2000 setara dengan mean equinox of date versi DE200/LE200.
           Perbedaan dengan presesi modern (IAU2006) pada 2024 < 0.1″, diabaikan.

    Dengan koreksi equinox offset -0.053″, kedua sistem menggunakan kerangka apparent of-date
    yang setara dalam batas toleransi arkeoastronomi Jolotundo (±10″).
    ========================================================================
    """
    print("\n" + "="*80)
    print("  JAE LUNAR ELP2000-82B vs JPL HORIZONS (DE441) - VALIDASI")
    print("  Epoch: 2024-Dec-25 05:00:00 UT")
    print("  Sistem koordinat: APPARENT OF-DATE (GEOSENTRIK)")
    print("  Koreksi diterapkan: offset equinox -0.053″ (JPL terhadap IAU06/00a)")
    print("="*80)

    # --------------------------------------------------------------------
    # 1. Data JPL Horizons (diekstrak dari horizons_results (1).txt)
    #    Kolom: R.A.__(a-apparent)__DEC
    # --------------------------------------------------------------------
    jpl_ra_hms  = (13, 42, 30.77)      # 13h 42m 30.77s
    jpl_dec_dms = (-13, 1, 36.4)       # -13° 01' 36.4"
    jpl_dist_au = 0.00270017121431

    # Konversi ke derajat
    jpl_ra_deg = 15.0 * (jpl_ra_hms[0] + jpl_ra_hms[1]/60.0 + jpl_ra_hms[2]/3600.0)
    sign = -1 if jpl_dec_dms[0] < 0 else 1
    jpl_dec_deg = sign * (abs(jpl_dec_dms[0]) + jpl_dec_dms[1]/60.0 + jpl_dec_dms[2]/3600.0)
    jpl_dist_km = jpl_dist_au * IAU2023UltraPrecision.AU_TO_KM

    print("\n[REFERENSI JPL HORIZONS]")
    print(f"  RA (app.of-date): {jpl_ra_deg:.10f}°  ({jpl_ra_hms[0]:02d}h {jpl_ra_hms[1]:02d}m {jpl_ra_hms[2]:.2f}s)")
    print(f"  Dec(app.of-date): {jpl_dec_deg:.10f}°  ({abs(jpl_dec_dms[0]):02d}° {jpl_dec_dms[1]:02d}' {jpl_dec_dms[2]:.1f}\")")
    print(f"  Jarak geosentrik : {jpl_dist_au:.12f} AU ({jpl_dist_km:.3f} km)")

    # --------------------------------------------------------------------
    # 2. Hitung dengan JAE Lunar Engine (ELP2000-82B)
    # --------------------------------------------------------------------
    year_astro = 2024
    month = 12
    day = 25
    hour_utc = 5
    minute = 0
    second = 0

    time_sys = TimeSystem()
    lunar_engine = LunarELP82Engine()
    jd_utc = time_sys.date_to_jd_utc(year_astro, month, day, hour_utc, minute, second)

    result = lunar_engine.calculate_position(
        jd_utc,
        output_frame='equatorial_apparent',   # Apparent of-date (IAU06/00a style)
        use_gamma_prime_correction=True       # γ'2000 → mean equinox of date
    )

    jae_ra_deg  = result['equatorial_apparent']['ra_deg']
    jae_dec_deg = result['equatorial_apparent']['dec_deg']
    jae_dist_au = result['distance_au']
    jae_dist_km = result['distance_km']

    print("\n[JAE LUNAR ENGINE (ELP2000-82B)]")
    print(f"  RA (app.of-date, IAU06/00a): {jae_ra_deg:.10f}°")
    print(f"  Dec(app.of-date, IAU06/00a): {jae_dec_deg:.10f}°")
    print(f"  Jarak geosentrik           : {jae_dist_au:.12f} AU ({jae_dist_km:.3f} km)")

    # --------------------------------------------------------------------
    # 3. Koreksi kerangka koordinat: offset equinox
    #    JPL menggunakan kerangka dengan equinox offset -53 mas terhadap IAU06/00a.
    #    Untuk menyetarakan, RA JAE dikurangi 0.053″.
    # --------------------------------------------------------------------
    EQUINOX_OFFSET_ARCSEC = 0.053   # dari catatan JPL
    EQUINOX_OFFSET_DEG = EQUINOX_OFFSET_ARCSEC / 3600.0

    jae_ra_corrected_deg = jae_ra_deg - EQUINOX_OFFSET_DEG

    print(f"\n[KOREKSI EQUINOX OFFSET]")
    print(f"  Offset equinox JPL vs IAU06/00a : {EQUINOX_OFFSET_ARCSEC:.3f}″")
    print(f"  RA JAE setelah koreksi          : {jae_ra_corrected_deg:.10f}°")
    print(f"  (RA dikurangi {EQUINOX_OFFSET_DEG:.6f}°)")

    # --------------------------------------------------------------------
    # 4. Selisih (JAE - JPL) sebelum & sesudah koreksi
    # --------------------------------------------------------------------
    delta_ra_raw    = (jae_ra_deg - jpl_ra_deg) * 3600.0
    delta_dec       = (jae_dec_deg - jpl_dec_deg) * 3600.0
    delta_ra_corr   = (jae_ra_corrected_deg - jpl_ra_deg) * 3600.0
    delta_dist_km   = jae_dist_km - jpl_dist_km

    print("\n[PERBANDINGAN (JAE - JPL)]")
    print(f"  ΔRA (tanpa koreksi)  : {delta_ra_raw:+10.3f}″")
    print(f"  ΔRA (setelah koreksi): {delta_ra_corr:+10.3f}″")
    print(f"  ΔDec                 : {delta_dec:+10.3f}″")
    print(f"  ΔJarak               : {delta_dist_km:+10.3f} km")

    # --------------------------------------------------------------------
    # 5. Toleransi arkeoastronomi Jolotundo
    # --------------------------------------------------------------------
    tol_ra   = 10.0   # arcsec
    tol_dec  = 10.0
    tol_dist = 500.0  # km

    ra_pass  = abs(delta_ra_corr) < tol_ra
    dec_pass = abs(delta_dec)     < tol_dec
    dist_pass= abs(delta_dist_km) < tol_dist

