    def interpolate_eclipse_delta_t(self, year_hist):
        """
        Interpolasi ΔT dari data gerhana untuk tahun di antara anchor points
        Menggunakan interpolasi cosinus untuk transisi yang lebih halus.
        """
        if year_hist < 702 or year_hist > 1299:
            return None, 0.0

        # Cek apakah tahun tepat dalam data
        if year_hist in self.eclipse_delta_t_anchors:
            data = self.eclipse_delta_t_anchors[year_hist]
            return data['delta_t'], data['reliability']

        # Jika tidak, cari dua tahun terdekat
        years = sorted(self.eclipse_delta_t_anchors.keys())
        lower = None
        upper = None
        for y in years:
            if y < year_hist:
                lower = y
            elif y > year_hist:
                upper = y
                break
        if lower is None or upper is None:
            return None, 0.0

        data_lower = self.eclipse_delta_t_anchors[lower]
        data_upper = self.eclipse_delta_t_anchors[upper]
        
        # Interpolasi cosinus
        fraction = (year_hist - lower) / (upper - lower)
        mu2 = (1 - math.cos(fraction * math.pi)) / 2
        dt = data_lower['delta_t'] * (1 - mu2) + data_upper['delta_t'] * mu2
        rel = data_lower['reliability'] * (1 - mu2) + data_upper['reliability'] * mu2
        
        return dt, rel

    def delta_t_eclipse_corrected(self, year_astro):
        """
        ΔT dengan koreksi data gerhana untuk rentang 700-1300 AD
        """
        if year_astro <= 0:
            year_hist = year_astro - 1
        else:
            year_hist = year_astro

        if year_hist < 702 or year_hist > 1299:
            return self.delta_t_espenak_extended(year_astro)

        dt_eclipse, reliability = self.interpolate_eclipse_delta_t(year_hist)

        if dt_eclipse is None:
            return self.delta_t_espenak_extended(year_astro)

        return dt_eclipse

