    def _apply_precession_j2000_to_date(self, ra_deg: float, dec_deg: float, 
                                       T: float) -> Tuple[float, float]:
        """Apply precession from J2000 to of-date (IAU 2006)."""
        # Convert to radians
        ra_rad = math.radians(ra_deg)
        dec_rad = math.radians(dec_deg)
        
        # Precession parameters (IAU 2006)
        eta = math.radians((47.0213 * T - 0.03302 * T**2 + 0.000060 * T**3) / 3600.0)
        zeta = math.radians((47.0213 * T - 0.03302 * T**2 + 0.000060 * T**3) / 3600.0)
        theta = math.radians((20042.0207 * T - 0.03302 * T**2 + 0.000060 * T**3) / 3600.0)
        
        # Apply precession matrix
        cos_dec = math.cos(dec_rad)
        sin_dec = math.sin(dec_rad)
        
        # Simplified precession (for high accuracy, use full matrix multiplication)
        A = math.cos(ra_rad + zeta) * cos_dec
        B = math.sin(ra_rad + zeta) * cos_dec
        C = sin_dec
        
        ra_precessed_rad = math.atan2(B * math.cos(theta) - C * math.sin(theta), A) - eta
        dec_precessed_rad = math.asin(B * math.sin(theta) + C * math.cos(theta))
        
        return math.degrees(ra_precessed_rad) % 360, math.degrees(dec_precessed_rad)
    
    def _apply_nutation(self, ra_deg: float, dec_deg: float, 
                       T: float) -> Tuple[float, float, float, float]:
        """Apply nutation correction (IAU 2000A)."""
        # Use the HighPrecisionNutation class
        nutation = HighPrecisionNutation()
        dPsi_rad, dEps_rad = nutation.compute(T)
        
        # Convert to degrees
        dPsi_deg = math.degrees(dPsi_rad)
        dEps_deg = math.degrees(dEps_rad)
        
        # Mean obliquity
        eps0_rad = math.radians(23.4392911 - 0.0130042 * T - 0.00000016 * T**2)
        
        # Nutation in right ascension and declination
        ra_rad = math.radians(ra_deg)
        dec_rad = math.radians(dec_deg)
        
        delta_ra = (math.cos(eps0_rad) + math.sin(eps0_rad) * math.sin(ra_rad) * math.tan(dec_rad)) * dPsi_deg
        delta_ra -= (math.cos(ra_rad) * math.tan(dec_rad)) * dEps_deg
        
        delta_dec = (math.sin(eps0_rad) * math.cos(ra_rad)) * dPsi_deg
        delta_dec += math.sin(ra_rad) * dEps_deg
        
        ra_nutated_deg = ra_deg + delta_ra
        dec_nutated_deg = dec_deg + delta_dec
        
        return ra_nutated_deg % 360, dec_nutated_deg, dPsi_deg, dEps_deg
    
    def _apply_annual_aberration(self, ra_deg: float, dec_deg: float,
                                distance_au: float, T: float) -> Tuple[float, float]:
        """Apply annual aberration correction."""
        # Constant of aberration (arcseconds)
        k_arcsec = 20.49552
        k_deg = k_arcsec / 3600.0
        
        # Earth's orbital velocity direction (simplified - towards solar apex)
        # For precise calculation, need Earth's velocity vector from VSOP87
        L_sun_deg = 280.46646 + 36000.76983 * T + 0.0003032 * T**2
        L_sun_rad = math.radians(L_sun_deg % 360)
        
        ra_rad = math.radians(ra_deg)
        dec_rad = math.radians(dec_deg)
        
        # Aberration correction (simplified formula)
        delta_ra = -k_deg / math.cos(dec_rad) * math.sin(ra_rad - L_sun_rad)
        delta_dec = -k_deg * math.cos(ra_rad - L_sun_rad) * math.sin(dec_rad)
        
        ra_aberrated_deg = ra_deg + delta_ra
        dec_aberrated_deg = dec_deg + delta_dec
        
        return ra_aberrated_deg % 360, dec_aberrated_deg
    
    def _apply_diurnal_aberration(self, ra_deg: float, dec_deg: float,
                                 observer_lat_deg: float, hour_angle_deg: float) -> Tuple[float, float]:
        """Apply diurnal aberration correction (due to Earth's rotation)."""
        # Earth's rotation velocity at equator (km/s)
        v_equator_km_s = 0.4651  # cos(lat) * 0.4651
        
        # Observer's velocity (depends on latitude)
        lat_rad = math.radians(observer_lat_deg)
        v_observer_km_s = v_equator_km_s * math.cos(lat_rad)
        
        # Speed of light in km/s
        c_km_s = 299792.458
        
        # Diurnal aberration constant
        k_diurnal_arcsec = math.degrees(v_observer_km_s / c_km_s) * 3600.0
        
        # Correction in hour angle (converted to RA)
        hour_angle_rad = math.radians(hour_angle_deg)
        dec_rad = math.radians(dec_deg)
        
        delta_ha_rad = k_diurnal_arcsec / 3600.0 * math.pi/180.0 * math.cos(lat_rad) * math.cos(hour_angle_rad) / math.cos(dec_rad)
        delta_ra_arcsec = -math.degrees(delta_ha_rad) * 3600.0  # Convert back to arcsec
        
        # Correction in declination
        delta_dec_arcsec = -k_diurnal_arcsec * math.cos(lat_rad) * math.sin(hour_angle_rad) * math.sin(dec_rad)
        
        return delta_ra_arcsec, delta_dec_arcsec
    
