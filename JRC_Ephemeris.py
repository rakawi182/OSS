class JPLStyleTopocentricCorrections:
    """
    JPL Horizons-style topocentric corrections with complete transformation chain.
    IMPROVED WITH KEY CONSISTENCY FIXES
    """
    
    def __init__(self):
        self.const = IAU2023UltraPrecision()
        self.time_sys = TimeSystem()
        self.atmosphere = AtmosphericModel()
        self.transformer = UnifiedCoordinateTransformer()
        self.cache = GlobalCacheManager.get_instance()
        
        # Earth parameters for topocentric corrections
        self.earth_equatorial_radius_km = self.const.EARTH_EQUATORIAL_RADIUS / 1000.0
        self.earth_flattening = self.const.EARTH_FLATTENING
    
    # ============================================================================
    # CORE TRANSFORMATION FUNCTIONS - GEOCENTRIC TO TOPOCENTRIC
    # ============================================================================
    
    def geocentric_to_topocentric_equatorial(self, ra_geocentric_deg: float, dec_geocentric_deg: float,
                                           distance_au: float, jd_utc: float,
                                           observer_lat_deg: float, observer_lon_deg: float,
                                           observer_elevation_m: float = 0.0) -> Dict[str, float]:
        """
        Convert geocentric equatorial coordinates to topocentric equatorial coordinates.
        Corrects for diurnal parallax (geocentric vs topocentric observer position).
        
        Steps (JPL Horizons method):
        1. Calculate observer geocentric position vector in equatorial coordinates
        2. Calculate geocentric object vector
        3. Compute topocentric vector = geocentric vector - observer vector
        4. Convert back to spherical coordinates
        
        Returns: topocentric RA, Dec in degrees
        """
        cache_key = f"geo2topo_eq_{ra_geocentric_deg:.8f}_{dec_geocentric_deg:.8f}_{jd_utc:.10f}_{observer_lat_deg:.6f}_{observer_lon_deg:.6f}"
        
        def compute():
            # Convert to radians
            ra_geo_rad = math.radians(ra_geocentric_deg)
            dec_geo_rad = math.radians(dec_geocentric_deg)
            
            # 1. Calculate geocentric position vector of the object
            # Distance in km
            distance_km = distance_au * self.const.AU_TO_KM
            x_geo = distance_km * math.cos(dec_geo_rad) * math.cos(ra_geo_rad)
            y_geo = distance_km * math.cos(dec_geo_rad) * math.sin(ra_geo_rad)
            z_geo = distance_km * math.sin(dec_geo_rad)
            
            # 2. Calculate observer position vector in equatorial coordinates
            # First: observer position in Earth-fixed coordinates (WGS84)
            x_obs_ef, y_obs_ef, z_obs_ef = self._calculate_observer_earth_fixed(
                observer_lat_deg, observer_lon_deg, observer_elevation_m
            )
            
            # Second: rotate to equatorial coordinates using GAST
            gast_rad = self._calculate_greenwich_apparent_sidereal_time(jd_utc)
            x_obs_eq, y_obs_eq, z_obs_eq = self._rotate_earth_fixed_to_equatorial(
                x_obs_ef, y_obs_ef, z_obs_ef, gast_rad
            )
            
            # 3. Compute topocentric vector
            x_topo = x_geo - x_obs_eq
            y_topo = y_geo - y_obs_eq
            z_topo = z_geo - z_obs_eq
            
            # 4. Convert to spherical coordinates (RA, Dec)
            distance_topo_km = math.sqrt(x_topo**2 + y_topo**2 + z_topo**2)
            
            if distance_topo_km == 0:
                return {'ra_topo_deg': ra_geocentric_deg, 'dec_topo_deg': dec_geocentric_deg}
            
            # Topocentric declination
            dec_topo_rad = math.asin(z_topo / distance_topo_km)
            
            # Topocentric right ascension
            ra_topo_rad = math.atan2(y_topo, x_topo)
            if ra_topo_rad < 0:
                ra_topo_rad += 2 * math.pi
            
            # Calculate parallax correction
            parallax_correction_ra = math.degrees(ra_topo_rad - ra_geo_rad) * 3600  # arcsec
            if parallax_correction_ra > 180 * 3600:
                parallax_correction_ra -= 360 * 3600
            elif parallax_correction_ra < -180 * 3600:
                parallax_correction_ra += 360 * 3600
                
            parallax_correction_dec = math.degrees(dec_topo_rad - dec_geo_rad) * 3600  # arcsec
            
            return {
                'ra_topo_deg': math.degrees(ra_topo_rad) % 360,
                'dec_topo_deg': math.degrees(dec_topo_rad),
                'ra_topo_rad': ra_topo_rad,
                'dec_topo_rad': dec_topo_rad,
                'distance_topo_km': distance_topo_km,
                'distance_topo_au': distance_topo_km / self.const.AU_TO_KM,
                'parallax_correction_ra_arcsec': parallax_correction_ra,
                'parallax_correction_dec_arcsec': parallax_correction_dec,
                'parallax_angle_arcsec': math.degrees(math.asin(self.earth_equatorial_radius_km / distance_km)) * 3600,
                'observer_vector_km': [x_obs_eq, y_obs_eq, z_obs_eq]
            }
        
        return self.cache.get_or_compute('coordinate', cache_key, compute)
    
    def _calculate_observer_earth_fixed(self, lat_deg: float, lon_deg: float, 
                                       elevation_m: float) -> Tuple[float, float, float]:
        """Calculate observer position in Earth-fixed coordinates (WGS84)."""
        lat_rad = math.radians(lat_deg)
        lon_rad = math.radians(lon_deg)
        
        # WGS84 ellipsoid parameters
        a = self.earth_equatorial_radius_km  # equatorial radius in km
        f = self.earth_flattening
        e2 = 2*f - f*f  # eccentricity squared
        
        # Calculate prime vertical radius of curvature
        sin_lat = math.sin(lat_rad)
        N = a / math.sqrt(1 - e2 * sin_lat * sin_lat)
        
        # Convert elevation to km
        h = elevation_m / 1000.0
        
        # Earth-fixed coordinates (ECEF)
        x = (N + h) * math.cos(lat_rad) * math.cos(lon_rad)
        y = (N + h) * math.cos(lat_rad) * math.sin(lon_rad)
        z = ((1 - e2) * N + h) * math.sin(lat_rad)
        
        return x, y, z
    
    def _calculate_greenwich_apparent_sidereal_time(self, jd_utc: float) -> float:
        """Calculate Greenwich Apparent Sidereal Time (GAST) in radians."""
        # Convert UTC to UT1 (approximation: UT1 ≈ UTC for this purpose)
        jd_ut1 = jd_utc
        
        # Calculate Greenwich Mean Sidereal Time
        T = (jd_ut1 - 2451545.0) / 36525.0
        GMST_sec = 24110.54841 + 8640184.812866 * T + 0.093104 * T**2 - 0.0000062 * T**3
        GMST_rad = (GMST_sec % 86400) / 86400.0 * 2 * math.pi
        
        # Add equation of equinoxes (nutation in longitude * cos(obliquity))
        # For higher accuracy, we'd calculate nutation properly
        dPsi_rad = 0.0  # Simplified - would need nutation calculation
        
        # Mean obliquity
        eps_rad = math.radians(23.4392911 - 0.0130042 * T - 0.00000016 * T**2)
        
        # Equation of equinoxes
        eqeq_rad = dPsi_rad * math.cos(eps_rad)
        
        # Greenwich Apparent Sidereal Time
        GAST_rad = GMST_rad + eqeq_rad
        
        return GAST_rad % (2 * math.pi)
    
    def _rotate_earth_fixed_to_equatorial(self, x: float, y: float, z: float, 
                                         gast_rad: float) -> Tuple[float, float, float]:
        """Rotate Earth-fixed coordinates to equatorial coordinates using GAST."""
        cos_gast = math.cos(gast_rad)
        sin_gast = math.sin(gast_rad)
        
        x_eq = x * cos_gast + y * sin_gast
        y_eq = -x * sin_gast + y * cos_gast
        z_eq = z  # Z axis is same in both systems
        
        return x_eq, y_eq, z_eq
    
